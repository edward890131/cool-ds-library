#!/usr/bin/env node
// build-pulso-icons.mjs（Goons DS Studio 專屬）
// 把網站用到的 PulsoIcon 圖示資料＋播放器內嵌進 library/gallery.html。
//
// 為什麼：本 DS 的 icon set 從 Phosphor 換成 PulsoIcon（線框／實心、可調線寬、每顆有專屬動態）。
// 網站是單一 HTML，要離線也能顯示、能播動態，所以把「實際用到的圖示資料」和播放器打包內嵌，
// 不在執行時依賴 CDN（只有 Icon 頁的「搜尋完整圖示庫」會連 CDN）。
//
// 做法：
//   1. 掃 gallery.html 裡所有 PI('key') 呼叫與 <!--PI:key--> 靜態標記，收集用到的 icon key
//   2. 從 pulsoicon-core 讀每顆的資料（形狀、動態、實心畫法）
//   3. 用 esbuild 把 pulsoicon-core 的 iconFrame／frameMarkup／playIcon ＋ motion 打成一支 IIFE（window.PulsoCore）
//   4. 改寫 gallery.html 內 /* PULSO:BEGIN */ … /* PULSO:END */ 區塊；HTML 裡的 <!--PI:key-->…<!--/PI--> 直接烤成靜態 SVG
//
// 用法：cd sync/pulso && npm install   （第一次）
//       node sync/build-pulso-icons.mjs
// 換版本：改 sync/pulso/package.json 的 pulsoicon-core／motion 版本 → npm install → 重跑本腳本。

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadIcon, markup, bundleRuntime, hasIcon, PULSO_VERSION, MOTION_VERSION } from "./pulso/lib.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const GALLERY = join(__dirname, "..", "library/gallery.html");
let src = readFileSync(GALLERY, "utf8");

// ── 1. 收集用到的 key ──
const keys = new Set();
for (const m of src.matchAll(/\bPI\('([a-z0-9-]+)'/g)) keys.add(m[1]);
for (const m of src.matchAll(/<!--PI:([a-z0-9-]+)-->/g)) keys.add(m[1]);
const bad = [...keys].filter((k) => !hasIcon(k));
if (bad.length) { console.error("✗ PulsoIcon 找不到這些 icon：" + bad.join("、")); process.exit(1); }

// ── 2. 圖示資料 ──
const icons = {};
for (const k of [...keys].sort()) icons[k] = await loadIcon(k);

// ── 3. 播放器 ──
const runtime = (await bundleRuntime()).replace(/<\/script/gi, "<\\/script");
const json = JSON.stringify(icons).replace(/<\/script/gi, "<\\/script");

const block = `/* PULSO:BEGIN ── 由 sync/build-pulso-icons.mjs 產生，勿手改（改圖示請改 PI('key') 呼叫後重跑腳本）
   PulsoIcon ${PULSO_VERSION}（https://github.com/CityPulso/PulsoIcon）· ISC License · Copyright (c) 2026 CityPulso
     部分形狀源自 Lucide（ISC）、Tabler Icons（MIT）、Iconoir（MIT）、Hugeicons（MIT）、Phosphor（MIT）
     完整授權條款見 library/THIRD_PARTY_NOTICES.md
   Motion ${MOTION_VERSION}（https://motion.dev）· MIT License · Copyright (c) 2024 Motion B.V. */
${runtime}
const PULSO_VERSION='${PULSO_VERSION}';
const PULSO_ICONS=${json};
/* PULSO:END */`;

const B = "/* PULSO:BEGIN", E = "/* PULSO:END */";
if (src.includes(B)) {
  const i = src.indexOf(B), j = src.indexOf(E, i) + E.length;
  src = src.slice(0, i) + block + src.slice(j);
} else {
  // 第一次：插在主程式 <script> 最前面（所有 PI() 呼叫之前）
  const anchor = "\n<script>\n";
  const at = src.indexOf(anchor);
  if (at < 0) { console.error("✗ 找不到主程式 <script>"); process.exit(1); }
  src = src.slice(0, at + anchor.length) + block + "\n" + src.slice(at + anchor.length);
}

// ── 4. HTML 靜態標記烤成 SVG（<!--PI:key-->[舊輸出<!--/PI-->]）──
src = src.replace(/<!--PI:([a-z0-9-]+)-->(?:[\s\S]*?<!--\/PI-->)?/g, (_, k) => `<!--PI:${k}-->${markup(icons[k])}<!--/PI-->`);

writeFileSync(GALLERY, src);

// ── 5. 第三方授權聲明（PulsoIcon 授權要求：網站內含 PulsoIcon 時須附上它的 LICENSE 全文；motion 為 MIT）──
const lic = (pkg, file) => readFileSync(join(__dirname, "pulso/node_modules", pkg, file), "utf8").trim();
writeFileSync(join(__dirname, "..", "library/THIRD_PARTY_NOTICES.md"), `# Third-party notices

此檔由 \`sync/build-pulso-icons.mjs\` 自動產生，勿手改。\`library/gallery.html\` 內嵌了以下第三方程式與圖示資料。
This file is generated by \`sync/build-pulso-icons.mjs\`. \`library/gallery.html\` bundles the following third-party code and icon data.

## PulsoIcon ${PULSO_VERSION} (pulsoicon-core)

https://github.com/CityPulso/PulsoIcon — 包含 Lucide、Tabler Icons、Iconoir、Hugeicons、Phosphor 的授權聲明。

\`\`\`
${lic("pulsoicon-core", "LICENSE")}
\`\`\`

## Motion ${MOTION_VERSION}

https://motion.dev

\`\`\`
${lic("motion", "LICENSE.md")}
\`\`\`
`);
console.log(`\n✓ PulsoIcon ${PULSO_VERSION} → gallery.html：內嵌 ${keys.size} 顆 icon、播放器 ${(runtime.length / 1024).toFixed(1)} KB、資料 ${(json.length / 1024).toFixed(1)} KB\n`);
